#!/usr/bin/env python3
"""True state values of the 1000-state random walk (Example 9.1) under the
random policy, gamma = 1: from state s jump uniformly 1..100 states left or
right; leaving the left end pays -1 and terminates, leaving the right end pays
+1. Asynchronous DP to a 1e-12 sweep change. Prints lib/oracle/walk1000-exact.aura."""
N, K = 1000, 100
v = [0.0] * (N + 2)
for s in range(1, N + 1):
    v[s] = (2.0 * s - (N + 1)) / (N + 1)
sweeps = 0
while True:
    delta = 0.0
    for s in range(1, N + 1):
        x = 0.0
        for d in (-1, 1):
            for k in range(1, K + 1):
                t = s + d * k
                x += -1.0 if t < 1 else (1.0 if t > N else v[t])
        x /= 2 * K
        delta = max(delta, abs(x - v[s]))
        v[s] = x
    sweeps += 1
    if delta < 1e-12:
        break
print("; oracle/walk1000-exact.aura — generated by tests/oracle/walk1000_exact.py (exact DP,")
print("; %d sweeps). True v_pi of the 1000-state random walk; index 0 and 1001 are the" % sweeps)
print("; terminals (0). Do not edit by hand.")
print("(export w1k-true)")
print("(define w1k-true (vector 0.0")
row = []
for s in range(1, N + 1):
    row.append("%.6f" % v[s])
    if len(row) == 10:
        print("  " + " ".join(row)); row = []
print("  0.0))")
